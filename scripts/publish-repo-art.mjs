/**
 * Gives each project's GitHub repo a banner and a proper README, built from the
 * same data that drives the site, so a project with no hosted demo still shows
 * something worth looking at.
 *
 *   SITE_URL=https://example.com node scripts/publish-repo-art.mjs [flags]
 *
 * Flags:
 *   --dry-run       print what each repo would get, push nothing
 *   --print         with --dry-run, dump the first repo's generated README
 *   --all           include projects that already have a live demo
 *   --keep-readme   only put the banner on top of the existing README
 *
 * Per repo it:
 *   1. commits the banner to .github/social-preview.png
 *   2. rewrites README.md from lib/projects.js — banner, title, tagline,
 *      badges, what it is, how it works, highlights, tech, link to the write-up.
 *      Anything already in the README is kept in a collapsed "Original README"
 *      section, so nothing is lost.
 *   3. sets the repo description and homepage (gh repo edit)
 *
 * Re-running is safe: the markers below let it replace its own output instead of
 * stacking a second copy. Needs `gh auth login` first.
 *
 * GitHub has no API for the social preview card shown when a repo link is
 * shared; that is Settings > General > Social preview, by hand, one repo at a
 * time. The same public/projects/art/<slug>-social.png files work there.
 */

import { execFile } from "node:child_process";
import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

import { githubRepos } from "../lib/projects.js";
import { languageColors } from "../lib/languageColors.js";

const run = promisify(execFile);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OWNER = "Kurtis24";
const IMAGE_PATH = ".github/social-preview.png";

const GENERATED = "<!-- generated by scripts/publish-repo-art.mjs in Kurtis24/Website -->";
const BANNER_START = "<!-- project-banner -->";
const BANNER_END = "<!-- /project-banner -->";
const ORIGINAL_START = "<!-- original-readme -->";
const ORIGINAL_END = "<!-- /original-readme -->";

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const all = args.includes("--all");
const keepReadme = args.includes("--keep-readme");
const printFirst = args.includes("--print");
const siteUrl = (process.env.SITE_URL || "").replace(/\/$/, "");

if (!siteUrl && !dryRun) {
  console.error("SITE_URL is required, e.g. SITE_URL=https://example.com npm run art:publish");
  process.exit(1);
}

/* ── gh plumbing ────────────────────────────────────────────────────────── */

async function gh(ghArgs, options = {}) {
  try {
    const { stdout } = await run("gh", ghArgs, { maxBuffer: 32 * 1024 * 1024, ...options });
    return stdout;
  } catch (err) {
    throw new Error(`gh ${ghArgs.slice(0, 3).join(" ")}: ${err.stderr?.trim() || err.message}`);
  }
}

/** Existing file on the default branch, or null when it is not there yet. */
async function getFile(repo, path) {
  try {
    const json = JSON.parse(await gh(["api", `repos/${OWNER}/${repo}/contents/${path}`]));
    return { sha: json.sha, content: Buffer.from(json.content, "base64").toString("utf8") };
  } catch (err) {
    if (/404|Not Found/i.test(err.message)) return null;
    throw err;
  }
}

/** Commit a file through the contents API, passing the body on stdin. */
async function putFile(repo, path, contentBase64, message, sha) {
  await gh(["api", "-X", "PUT", `repos/${OWNER}/${repo}/contents/${path}`, "--input", "-"], {
    input: JSON.stringify({ message, content: contentBase64, ...(sha ? { sha } : {}) })
  });
}

/* ── README ─────────────────────────────────────────────────────────────── */

const SHIELD_LOGOS = {
  Swift: "swift",
  Python: "python",
  TypeScript: "typescript",
  JavaScript: "javascript",
  "C++": "cplusplus",
  CSS: "css3"
};

const shield = (label, color, extra = "") =>
  `https://img.shields.io/badge/${encodeURIComponent(label)}-${color}?style=for-the-badge${extra}`;

function badges(project) {
  const out = [];

  if (project.language) {
    const color = (languageColors[project.language] || "#6b7280").replace("#", "");
    const logo = SHIELD_LOGOS[project.language];
    out.push(
      `![${project.language}](${shield(project.language, color, logo ? `&logo=${logo}&logoColor=white` : "")})`
    );
  }
  if (project.kind) out.push(`![${project.kind}](${shield(project.kind, "1f2937")})`);

  out.push(
    `![Stars](https://img.shields.io/github/stars/${OWNER}/${project.name}?style=for-the-badge&color=f5c451&labelColor=1f2937)`,
    `![Last commit](https://img.shields.io/github/last-commit/${OWNER}/${project.name}?style=for-the-badge&color=74c69d&labelColor=1f2937)`
  );
  return out.join(" ");
}

const bannerBlock = (project) =>
  `${BANNER_START}\n<img src="${IMAGE_PATH}" alt="${project.title}" width="100%">\n${BANNER_END}`;

/**
 * Whatever was in the README before this script first touched it. Pulled back
 * out of its own collapsed section on a re-run so it never nests or gets lost.
 */
function extractOriginal(existing) {
  if (!existing) return "";

  const start = existing.indexOf(ORIGINAL_START);
  if (start !== -1) {
    const end = existing.indexOf(ORIGINAL_END);
    return existing
      .slice(start + ORIGINAL_START.length, end === -1 ? undefined : end)
      .replace(/^\s*<details>\s*<summary>[^<]*<\/summary>/i, "")
      .replace(/<\/details>\s*$/i, "")
      .trim();
  }

  if (existing.includes(GENERATED)) return "";
  return existing.trim();
}

function buildReadme(project, existing, landingUrl) {
  // Banner-only mode: leave their prose alone, just make sure the image is on top
  if (keepReadme && existing?.trim()) {
    const banner = bannerBlock(project);
    if (existing.includes(BANNER_START)) {
      const start = existing.indexOf(BANNER_START);
      const end = existing.indexOf(BANNER_END) + BANNER_END.length;
      return existing.slice(0, start) + banner + existing.slice(end);
    }
    return `${banner}\n\n${existing.replace(/^\n+/, "")}`;
  }

  const original = extractOriginal(existing);
  const lines = [
    GENERATED,
    bannerBlock(project),
    "",
    `# ${project.title}`,
    "",
    `> **${project.tagline}**`,
    "",
    badges(project),
    "",
    project.summary,
    ""
  ];

  if (project.overview) lines.push("## What it is", "", project.overview, "");

  if (project.howItWorks?.length) {
    lines.push("## How it works", "");
    project.howItWorks.forEach((step, i) => lines.push(`${i + 1}. ${step}`));
    lines.push("");
  }

  if (project.highlights?.length) {
    lines.push("## Highlights", "");
    project.highlights.forEach((item) => lines.push(`- ${item}`));
    lines.push("");
  }

  if (project.tech?.length) {
    lines.push("## Built with", "", project.tech.map((t) => `\`${t}\``).join(" · "), "");
  }

  if (project.homepage) {
    lines.push("## Try it", "", `[${project.homepage}](${project.homepage})`, "");
  }

  lines.push(
    "---",
    "",
    `<sub><b><a href="${landingUrl}">Full write-up →</a></b> · This README and the banner are generated ` +
      `from the project data in my <a href="https://github.com/${OWNER}/Website">portfolio repo</a>.</sub>`,
    ""
  );

  if (original) {
    lines.push(
      ORIGINAL_START,
      "<details>",
      "<summary>Original README</summary>",
      "",
      original,
      "",
      "</details>",
      ORIGINAL_END,
      ""
    );
  }

  return lines.join("\n");
}

/* ── run ────────────────────────────────────────────────────────────────── */

const targets = githubRepos.filter((p) => all || !p.homepage);
console.log(
  `${targets.length} repo(s)${all ? "" : ", skipping projects that already have a live demo"}` +
    `${keepReadme ? ", banner only" : ""}${dryRun ? " [dry run]" : ""}\n`
);

let failures = 0;

for (const project of targets) {
  const repo = project.name;
  const landingUrl = `${siteUrl}/projects/${project.slug}`;
  const pngPath = join(ROOT, "public", "projects", "art", `${project.slug}-social.png`);

  try {
    const png = await readFile(pngPath);
    const existingReadme = await getFile(repo, "README.md").catch(() => null);
    const readme = buildReadme(project, existingReadme?.content, landingUrl);

    if (dryRun) {
      const kept = extractOriginal(existingReadme?.content);
      console.log(
        `  ${repo}\n` +
          `    banner    ${IMAGE_PATH}  ${Math.round(png.length / 1024)}KB\n` +
          `    readme    ${existingReadme ? "rewrite" : "create"}, ${readme.split("\n").length} lines` +
          `${kept ? `, keeping ${kept.split("\n").length} original lines collapsed` : ""}\n` +
          `    homepage  ${landingUrl}`
      );
      if (printFirst && project === targets[0]) {
        console.log(`\n${"─".repeat(70)}\n${readme}${"─".repeat(70)}\n`);
      }
      continue;
    }

    const existingImage = await getFile(repo, IMAGE_PATH);
    await putFile(
      repo,
      IMAGE_PATH,
      png.toString("base64"),
      `${existingImage ? "Update" : "Add"} project banner`,
      existingImage?.sha
    );

    if (existingReadme?.content !== readme) {
      await putFile(
        repo,
        "README.md",
        Buffer.from(readme, "utf8").toString("base64"),
        existingReadme ? "Rewrite README with banner and project details" : "Add README",
        existingReadme?.sha
      );
    }

    await gh([
      "repo",
      "edit",
      `${OWNER}/${repo}`,
      "--description",
      project.summary,
      "--homepage",
      landingUrl
    ]);

    console.log(`  ✓ ${repo}`);
  } catch (err) {
    failures += 1;
    console.error(`  ✗ ${repo}: ${err.message}`);
  }
}

console.log(
  `\n${targets.length - failures}/${targets.length} done` +
    (failures ? `, ${failures} failed` : "") +
    (dryRun ? " (nothing was pushed)" : "")
);
if (failures) process.exitCode = 1;
